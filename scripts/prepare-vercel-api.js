// scripts/prepare-vercel-api.js
// Post-build step: injects the bundled server.cjs into the Vercel /api handler
// so @vercel/node can require the Express app without re-bundling.

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = process.cwd();
const API_DIR = path.join(PROJECT_ROOT, 'api');
const DIST_SERVER = path.join(PROJECT_ROOT, 'dist-server', 'server.cjs');

if (!fs.existsSync(DIST_SERVER)) {
  console.error('[prepare-vercel-api] ERROR: dist-server/server.cjs not found. Run build:server first.');
  process.exit(1);
}

if (!fs.existsSync(API_DIR)) {
  fs.mkdirSync(API_DIR, { recursive: true });
}

// Hand-off handler: imports the compiled Express app and mounts it into Vercel's Node runtime
const handlerCode = `
// /api/index.js — auto-generated by scripts/prepare-vercel-api.js
// This bridges the full Express server (server.ts bundled as dist-server/server.cjs)
// into a single Vercel Serverless Function that answers all /api/* requests.
'use strict';

const path = require('path');
const fs = require('fs');

// Ensure the data directory exists for persistent JSON DB storage
const DATA_DIR = path.join('/tmp', 'maapsetu-data');
if (!fs.existsSync(DATA_DIR)) {
  try { fs.mkdirSync(DATA_DIR, { recursive: true }); } catch (_) {}
}
process.env.DATA_DIR = DATA_DIR;

// Make process.cwd() resolve to the deployment root so relative paths
// inside server.ts (data/, public/) find their files correctly.
const rootDir = path.resolve(__dirname, '..');
if (process.cwd() !== rootDir) {
  try { process.chdir(rootDir); } catch (_) {}
}

// The server bundle is copied alongside us; import the Express app factory.
// server.cjs calls startServer() at bottom of file — but it also listens on
// a port which we must prevent for Vercel. So wrap it:

// We will require the bundled server. However the bundle auto-starts the HTTP
// listener. To avoid that, we monkey-patch app.listen() to a no-op the first
// time, then export a (req, res) handler for Vercel.
let expressApp = null;

const Server = require(path.resolve(__dirname, '..', 'dist-server', 'server.cjs'));

// Find the exported app (if any) or find it via require.cache exports fallback.
if (Server && Server.app) {
  expressApp = Server.app;
} else {
  // server.ts probably doesn't export its app; fallback: boot via require() above
  // and search global/module scope. This branch should not be hit.
  console.warn('[vercel-api] Warning: Server bundle did not export .app — using best-effort fallback.');
}

// Wrap the Express app for Vercel's (req, res, next?) contract
module.exports = (req, res) => {
  if (!expressApp) {
    // Last-ditch: if Server.app was not exported, we need to recreate.
    // This is unreachable if server.ts exposes the app.
    res.status(500).json({ error: 'Express app not initialized on serverless function' });
    return;
  }

  // Normalize Vercel's raw request so Express middleware (body-parser, routing)
  // sees the same shape as Node HTTP IncomingMessage.
  if (!req.url && req.path) {
    const qs = (req.query && Object.keys(req.query).length)
      ? '?' + new URLSearchParams(req.query).toString()
      : '';
    req.url = (req.path || '/') + qs;
  }
  if (!req.method) req.method = 'GET';

  return expressApp(req, res);
};

// Also expose default export for ESM users
module.exports.default = module.exports;
`;

const OUT = path.join(API_DIR, 'index.js');
fs.writeFileSync(OUT, handlerCode, 'utf8');
console.log(`[prepare-vercel-api] Wrote Vercel API entry -> ${path.relative(PROJECT_ROOT, OUT)}`);
